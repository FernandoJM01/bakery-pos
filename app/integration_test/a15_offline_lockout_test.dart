class _FakeSecureStorage extends Fake implements FlutterSecureStorage {
  final Map<String, String> values = {};

  @override
  Future<String?> read({
    required String key,
    AppleOptions? iOptions,
    AndroidOptions? aOptions,
    LinuxOptions? lOptions,
    WebOptions? webOptions,
    AppleOptions? mOptions,
    WindowsOptions? wOptions,
  }) async => values[key];

  @override
  Future<void> write({
    required String key,
    required String? value,
    AppleOptions? iOptions,
    AndroidOptions? aOptions,
    LinuxOptions? lOptions,
    WebOptions? webOptions,
    AppleOptions? mOptions,
    WindowsOptions? wOptions,
  }) async {
    if (value != null) values[key] = value;
  }

  @override
  Future<void> delete({
    required String key,
    AppleOptions? iOptions,
    AndroidOptions? aOptions,
    LinuxOptions? lOptions,
    WebOptions? webOptions,
    AppleOptions? mOptions,
    WindowsOptions? wOptions,
  }) async => values.remove(key);

  @override
  Future<void> deleteAll({
    AppleOptions? iOptions,
    AndroidOptions? aOptions,
    LinuxOptions? lOptions,
    WebOptions? webOptions,
    AppleOptions? mOptions,
    WindowsOptions? wOptions,
  }) async => values.clear();
}

void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();

  group('A15 Offline Lockout Integration Test', () {
    late AppDatabase db;
    late SecureStorageService secureStorage;
    late TillAuthService authService;
    late GoRouter router;

    // Argon2id hash for '1234' generated by node argon2 package
    const validVerifier =
        r'$argon2id$v=19$m=65536,p=1,t=3$p6+vhCNw8VlT1Bnq34jEeg$cZv+IP6sdJhBnTqEB3+SsD8svzrLHXPiPpDEWJPp/54';

    final testStaff = StaffEntriesCompanion.insert(
      id: '0192e2b0-0020-7000-8000-000000000020',
      displayName: 'Carlos (Gerente)',
      role: 'BRANCH_MANAGER',
      offlinePinVerifier: validVerifier,
      pinUpdatedAt: DateTime.utc(2026, 1, 1),
    );

    setUp(() async {
      db = AppDatabase(NativeDatabase.memory());
      secureStorage = SecureStorageService(_FakeSecureStorage());

      // Dio that simulates server down / network unreachable
      final offlineDio = Dio(BaseOptions(baseUrl: 'http://localhost:3000'))
        ..interceptors.add(
          InterceptorsWrapper(
            onRequest: (options, handler) {
              handler.reject(
                DioException(
                  requestOptions: options,
                  type: DioExceptionType.connectionError,
                  error: const SocketException('Connection refused'),
                ),
              );
            },
          ),
        );

      final restClient = RestClient(offlineDio);
      authService = TillAuthService(
        restClient: restClient,
        database: db,
        secureStorage: secureStorage,
      );

      await db.replaceStaffBundle(
        staff: [testStaff],
        permissions: [
          RolePermissionsCompanion.insert(
            role: 'BRANCH_MANAGER',
            permissionKey: 'sale.create',
          ),
        ],
      );

      router = GoRouter(
        initialLocation: AppRoutes.tillLogin,
        routes: [
          GoRoute(
            path: AppRoutes.tillLogin,
            builder: (context, state) => const TillLoginScreen(),
          ),
          GoRoute(
            path: AppRoutes.tillHome,
            builder: (context, state) => const Scaffold(
              body: Text('till-home', key: Key('till-home-screen')),
            ),
          ),
        ],
      );
    });

    tearDown(() async {
      authService.dispose();
      await db.close();
      router.dispose();
    });

    testWidgets(
      'A15: Till offline: staff member is refused with wrong PIN and locked after 5 wrong attempts',
      (tester) async {
        await tester.pumpWidget(
          ProviderScope(
            overrides: [
              tillDatabaseProvider.overrideWithValue(db),
              secureStorageProvider.overrideWithValue(secureStorage),
              tillAuthServiceProvider.overrideWithValue(authService),
            ],
            child: MaterialApp.router(
              locale: const Locale('es', 'MX'),
              localizationsDelegates: AppLocalizations.localizationsDelegates,
              supportedLocales: AppLocalizations.supportedLocales,
              routerConfig: router,
            ),
          ),
        );
        await tester.pumpAndSettle();

        // 1. Staff tile is displayed and selected
        expect(
          find.byKey(
            const Key('staff-tile-0192e2b0-0020-7000-8000-000000000020'),
          ),
          findsOneWidget,
        );

        // Helper to enter 4 digits on keypad and press confirm
        Future<void> enterPinAndConfirm(String pin) async {
          for (int i = 0; i < pin.length; i++) {
            await tester.tap(find.byKey(Key('keypad-${pin[i]}')));
          }
          await tester.pump();
          await tester.runAsync(() async {
            await tester.tap(find.byKey(const Key('keypad-confirm')));
          });
          await tester.pumpAndSettle();
        }

        // Attempts 1 to 4: wrong PIN (9999), refused with 'PIN incorrecto'
        for (int i = 1; i <= 4; i++) {
          await enterPinAndConfirm('9999');
          expect(find.byKey(const Key('login-error-banner')), findsOneWidget);
          expect(find.text('PIN incorrecto'), findsOneWidget);
        }

        // Attempt 5: wrong PIN, triggers lockout!
        await enterPinAndConfirm('9999');
        expect(find.byKey(const Key('login-error-banner')), findsOneWidget);
        expect(find.textContaining('Bloqueado hasta las'), findsOneWidget);

        // Attempt 6 (even with the right PIN '1234'): remains locked!
        await enterPinAndConfirm('1234');
        expect(find.byKey(const Key('login-error-banner')), findsOneWidget);
        expect(find.textContaining('Bloqueado hasta las'), findsOneWidget);
      },
    );
  });
}
